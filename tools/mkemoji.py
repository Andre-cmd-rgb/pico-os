#!/usr/bin/env python3
"""Emoji for the terminal, two cells wide: tools/emoji.txt from an emoji font.

Each is drawn from Noto Color Emoji at 109 px and brought down to 11 x 10
pixels (two 6 x 10 cells, less a column between it and what follows):
a pixel is on where the emoji is, and off where it is dark or of a colour
far from its own, so a face keeps its eyes and mouth. Its colour is the
nearest of the terminal's sixteen to its own. Needs Pillow; tools/mkfont.py
then reads the text file, so `make font` does not.

    python3 tools/mkemoji.py > tools/emoji.txt
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/noto/NotoColorEmoji.ttf"
W, H = 11, 10

# The ones people use most (and the hearts in all their colours). The
# check marks stay one cell: the screen's ticks are made of them.
